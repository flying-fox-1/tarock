def igralne_karte(ime_karte_za_izris):
    karte_narisane = pridobi_karte_vse_izris()
    if ime_karte_za_izris in karte_narisane:
        return dedent(karte_narisane[ime_karte_za_izris]).strip("\n")
    else:
        return ime_karte_za_izris
    
def narisi_karte_v_roki(imena_kart, zamik=6):
    karte = [
        igralne_karte(ime).splitlines()
        for ime in imena_kart
    ]

    visina = len(karte[0])

    for vrstica in range(visina):
        izpis = ""

        for i, karta in enumerate(karte):
            if i == len(karte) - 1:
                # Zadnja karta je vidna v celoti
                izpis += karta[vrstica]
            else:
                # Ostalim pokaži samo levi del
                izpis += karta[vrstica][:zamik]

        print(izpis)
        
def izpiši_talon(talon):
    ime_kart = []
    for i in range(len(talon)):
        ime_kart.append(f"{talon[i][0]}_{talon[i][1]}")                 
    narisi_karte_v_roki(ime_kart)